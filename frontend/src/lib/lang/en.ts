/**
 * A translation: the same shape, every key optional, down to the leaves. A
 * function is a leaf — it is translated whole or not at all.
 */
export type Translation = DeepPartial<Dict>

type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends (...args: never[]) => unknown ? T[K] : T[K] extends object ? DeepPartial<T[K]> : T[K]
}
